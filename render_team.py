"""Render the verified second-paper results without altering their numeric scale.

python paper_team/render_team.py          # write generated LaTeX and manifest
python paper_team/render_team.py --check  # regenerate in memory and compare

Only data/current_results.json supplies experimental numbers. Rates are shown on
the percentage scale, costs have two decimals, and p-values retain their own scale.
"""
from __future__ import annotations
import argparse
from decimal import Decimal, ROUND_HALF_UP
from hashlib import sha256
import json
from pathlib import Path

HERE=Path(__file__).resolve().parent
SOURCE=HERE/'data/current_results.json'
NAMES={'mmlu_pro':'MMLU-Pro','math500':'MATH-500','gsm8k':'GSM8K'}
BENCHES=list(NAMES)


def fixed(x,places=1,scale=1,signed=False):
    value=Decimal(str(x))*Decimal(str(scale))
    value=value.quantize(Decimal(1).scaleb(-places),rounding=ROUND_HALF_UP)
    # Avoid displaying a signed negative zero after rounding.
    if value==0:value=abs(value)
    return f'{value:+.{places}f}' if signed else f'{value:.{places}f}'


def pct(x,signed=False):return fixed(x,1,100,signed)
def cost(x):return fixed(x,2)


def pv(x,relation=False):
    if Decimal(str(x))<Decimal('.001'):return '<0.001'
    return ('=' if relation else '')+fixed(x,3)


def ci(stat):
    return '$'+pct(stat['delta'],True)+r'\;['+pct(stat['ci'][0],True)+','+pct(stat['ci'][1],True)+']$'


def math(x):return '$'+x+'$'
def bold(x,yes):return r'\textbf{'+x+'}' if yes else x
def eq(x,y):return abs(x-y)<1e-12
def pool(tag):return math(tag.replace('x',r'\!\times\!'))


def table(caption,label,columns,header,rows,source_hash,groups=None):
    """Render a restrained header band, preserving data and natural table width.

    Optional (column count, title) groups identify different units or comparisons
    above the existing column labels.  Colour marks roles, never result rank.
    """
    placement = 'H' if label.startswith('tab:s-') else 'htbp'
    body=[]
    for row in rows:
        if row is None:
            body.append(r'\arrayrulecolor[HTML]{C8D1D8}\midrule'
                        r'\arrayrulecolor[HTML]{607381}')
        else:
            # Benchmark names identify experimental blocks; only the numeric
            # bold() calls below indicate a best result.
            cells=[r'\textbf{'+cell+'}' if cell in NAMES.values() else cell for cell in row]
            body.append(' & '.join(cells)+r' \\')
    labels=[]
    for cell in header:
        shade=r'\cellcolor{methodshade}' if cell in ('One-coin','Posterior') else ''
        labels.append(shade+r'{\bfseries '+cell+'}')
    header_text=r'\rowcolor[HTML]{EDF2F5}'+'\n'+' & '.join(labels)+r' \\'+'\n'
    if groups:
        assert sum(span for span,_ in groups)==len(header)
        titles=[];rules=[];start=1
        for span,title in groups:
            titles.append(r'\multicolumn{'+str(span)+r'}{c}{\bfseries '+title+'}')
            if title:rules.append(r'\cmidrule(lr){'+str(start)+'-'+str(start+span-1)+'}')
            start+=span
        header_text=(r'\rowcolor[HTML]{EDF2F5}'+'\n'+' & '.join(titles)+r' \\'+'\n'
                     +''.join(rules)+'\n'+header_text)
    return ('% Generated by render_team.py; source SHA256 '+source_hash+'\n'
        +r'\begin{table}['+placement+']\n'+r'\centering'+'\n'
        +r'\caption{'+caption+'}\n'+r'\label{'+label+'}\n'
        +r'\fontsize{8}{9.6}\selectfont'+'\n'
        +r'\setlength{\tabcolsep}{2.5pt}'+'\n'+r'\renewcommand{\arraystretch}{1.12}'+'\n'
        +r'\arrayrulecolor{black}'+'\n'
        +r'\setlength{\heavyrulewidth}{0.6pt}'+'\n'
        +r'\setlength{\lightrulewidth}{0.3pt}'+'\n'
        +r'\setlength{\cmidrulewidth}{0.3pt}'+'\n'
        +r'\sbox{\resulttablebox}{%'+'\n'+r'\begin{tabular}{'+columns+'}'+'\n'
        +r'\toprule\arrayrulecolor[HTML]{607381}'+'\n'+header_text+r'\midrule'+'\n'
        +'\n'.join(body)+'\n'+r'\arrayrulecolor{black}\bottomrule'+'\n'+r'\end{tabular}}'+'\n'
        +r'\ifdim\wd\resulttablebox>\columnwidth'+'\n'
        +r'\resizebox{\columnwidth}{!}{\usebox{\resulttablebox}}'+'\n'
        +r'\else\usebox{\resulttablebox}\fi'+'\n'+r'\end{table}'+'\n')


def render():
    raw=SOURCE.read_bytes();source_hash=sha256(raw).hexdigest()
    data=json.loads(raw);b=data['benchmarks'];out={}
    def put(name,caption,label,columns,header,rows,groups=None):
        out['tables/'+name]=table(caption,label,columns,header,rows,source_hash,groups)
    metrics=[p['gap_coverage'] for bench in ['mmlu_pro','math500'] for p in b[bench]['fixed_pools'].values()]
    stops=[b[bench]['stopping']['posterior_minimum_to_single9']['cost'] for bench in BENCHES]
    savings=[1-x/9 for x in stops]
    m=b['mmlu_pro'];mp=m['fixed_pools']['3x9'];a=m['allocation']['9']
    macro={
        'CoverageGapMin':pct(min(metrics))+r'\%',
        'CoverageGapMax':pct(max(metrics))+r'\%',
        'GsmCoverageGapMin':pct(min(p['gap_coverage'] for p in b['gsm8k']['fixed_pools'].values()))+r'\%',
        'GsmCoverageGapMax':pct(max(p['gap_coverage'] for p in b['gsm8k']['fixed_pools'].values()))+r'\%',
        'StopCallsMin':cost(min(stops)), 'StopCallsMax':cost(max(stops)),
        'StopSavingsMin':pct(min(savings))+r'\%', 'StopSavingsMax':pct(max(savings))+r'\%',
        'MmluStopCalls':cost(stops[0]),'MathStopCalls':cost(stops[1]),'GsmStopCalls':cost(stops[2]),
        'MmluOneCoinFull':pct(mp['onecoin'])+r'\%',
        'MmluCoverageFull':pct(mp['coverage_ceiling'])+r'\%',
        'MmluWeightedFull':pct(mp['cal_weighted'])+r'\%',
        'MmluWeightGainFull':pct(mp['weighted_minus_onecoin']['delta'],True)+r'\%',
        'MmluWeightPFull':pv(mp['weighted_minus_onecoin']['p_holm'],True),
        'MmluTwoNine':pct(a['two'])+r'\%', 'MmluThreeNine':pct(a['three'])+r'\%',
        'MmluAllocationGain':pct(a['two']-a['three'],True)+r'\%',
        'MmluWeakReliability':pct(mp['reliabilities'][m['order'][-1]])+r'\%',
        'MmluWeakCalibration':pct(m['cal9'][m['order'][-1]])+r'\%'}
    out['data/generated_numbers.tex']=('% Generated by render_team.py; source SHA256 '+source_hash+'\n'
        +'\n'.join('\\newcommand{\\'+k+'}{'+v+'}' for k,v in macro.items())+'\n')
    rows=[]
    for bench in BENCHES:
        r=b[bench];best=max(r['cal9'].values())
        rows.append([NAMES[bench],str(r['n_cal']),str(r['n_eval'])]+
                    [bold(pct(r['cal9'][m]),eq(r['cal9'][m],best)) for m in ['qwen','llama','mistral']])
    put('tab_setup_current.tex','Evaluation splits and calibration accuracy (\\%).','tab:setup',
        'lrrccc',['Benchmark',r'$n_c$',r'$n_e$','Qwen','Llama','Mistral'],rows,
        [(1,''),(2,'Split size'),(3,r'Calibration accuracy (\%)')])
    rows=[]
    for bench in BENCHES:
        rr=b[bench]['fixed_pools'].values()
        cg=[p['gap_coverage'] for p in rr];mg=[p['gap_member'] for p in rr]
        rows.append([NAMES[bench],pct(min(cg))+'--'+pct(max(cg)),pct(min(mg))+'--'+pct(max(mg))])
    put('tab_headroom_current.tex','Fixed-pool reference margins across pool shapes (\\%).','tab:headroom',
        'lcc',['Benchmark',r'$g_{\rm cov}$',r'$d_{\rm mem}$'],rows)
    rows=[];salloc=[];ssingle=[]
    for bench in BENCHES:
        if rows:rows.append(None);salloc.append(None);ssingle.append(None)
        for j,(B,r) in enumerate(b[bench]['allocation'].items()):
            best=max(r['two'],r['three']);name=NAMES[bench] if j==0 else ''
            stat=r['three_minus_two']
            rows.append([name,B,bold(pct(r['two']),eq(r['two'],best)),
                         bold(pct(r['three']),eq(r['three'],best)),
                         math(pct(stat['delta'],True)),math(pv(stat['p_holm']))])
            salloc.append([name,B,pct(r['two']),pct(r['three']),ci(stat),
                           math(pv(stat['p'])),math(pv(stat['p_holm']))])
            if r['single'] is not None:
                st=r['two_minus_single'];mx=max(r['single'],r['two'])
                ssingle.append([NAMES[bench] if B=='6' else '',B,
                    bold(pct(r['single']),eq(r['single'],mx)),bold(pct(r['two']),eq(r['two'],mx)),
                    ci(st),math(pv(st['p'])),math(pv(st['p_holm']))])
    put('tab_allocation_current.tex','Two- and three-member allocation at equal calls (\\%).','tab:allocation',
        'lrcccr',['Benchmark',r'$B$','Two','Three',r'$\Delta(3{-}2)$',r'$p_H$'],rows)
    put('tab_s_allocation.tex','Equal-call allocation comparisons (\\%).','tab:s-allocation',
        'lrccccc',['Benchmark',r'$B$','Two','Three',r'$\Delta(3{-}2)$ [95\% CI]',r'$p$',r'$p_H$'],salloc)
    put('tab_s_single.tex','Two members versus the strongest single-member arm (\\%).','tab:s-single',
        'lrccccc',['Benchmark',r'$B$','Single','Two',r'$\Delta(2{-}\mathrm{single})$ [95\% CI]',r'$p$',r'$p_H$'],ssingle)
    rows=[]
    for tag,r in m['fixed_pools'].items():
        mx=max(r[k] for k in ['majority','onecoin','cal_weighted']);st=r['weighted_minus_onecoin']
        rows.append([pool(tag),bold(pct(r['majority']),eq(r['majority'],mx)),
            bold(pct(r['onecoin']),eq(r['onecoin'],mx)),bold(pct(r['cal_weighted']),eq(r['cal_weighted'],mx)),
            math(pct(st['delta'],True)),math(pv(st['p_holm']))])
    put('tab_aggregation_current.tex','Readouts on identical MMLU-Pro pools (\\%).','tab:aggregation',
        r'lc>{\columncolor{methodshade}}cccr',
        ['Pool','Majority','One-coin','Cal.-wtd',r'$\Delta_{\rm cw}$',r'$p_H$'],rows,
        [(1,''),(3,r'Accuracy (\%)'),(2,'Comparison')])
    rows=[]
    for bench in BENCHES:
        st=b[bench]['stopping'];p=st['posterior_minimum_to_single9']
        cc=[st[k+'_minimum_to_single9']['cost'] if st[k+'_minimum_to_single9'] else None
            for k in ['fixed_stream','vote_threshold','posterior']]
        best=min(x for x in cc if x is not None)
        rows.append([NAMES[bench],pct(st['single9_reference']['accuracy'])]+
                    [bold(cost(x),eq(x,best)) if x is not None else '--' for x in cc]+
                    [pct(p['accuracy'])])
    put('tab_stopping_current.tex','Measured calls to the nine-call accuracy reference.','tab:stopping',
        r'lccc>{\columncolor{methodshade}}cc',
        ['Benchmark',r'Ref. (\%)','Fixed','Vote','Posterior',r'Posterior acc. (\%)'],rows,
        [(2,''),(3,'Mean online calls'),(1,'')])
    soracle=[];sread=[];smulti=[];scal=[]
    for bench in BENCHES:
        if soracle:soracle.append(None);sread.append(None);scal.append(None)
        for j,(tag,r) in enumerate(b[bench]['fixed_pools'].items()):
            name=NAMES[bench] if j==0 else '';st=r['weighted_minus_onecoin']
            soracle.append([name,pool(tag),str(r['budget']),pct(r['onecoin']),pct(r['coverage_ceiling']),
                           pct(r['member_selection_oracle']),pct(r['gap_coverage']),math(pct(r['gap_member'],True))])
            mx=max(r[k] for k in ['majority','onecoin','cal_weighted'])
            sread.append([name,pool(tag),bold(pct(r['majority']),eq(r['majority'],mx)),
                bold(pct(r['onecoin']),eq(r['onecoin'],mx)),bold(pct(r['cal_weighted']),eq(r['cal_weighted'],mx)),
                ci(st),math(pv(st['p'])),math(pv(st['p_holm']))])
            if r['multi_coin'] is not None:
                st=r['multicoin_minus_onecoin'];mx=max(r['onecoin'],r['multi_coin'])
                smulti.append([pool(tag),bold(pct(r['onecoin']),eq(r['onecoin'],mx)),
                    bold(pct(r['multi_coin']),eq(r['multi_coin'],mx)),ci(st),math(pv(st['p'])),math(pv(st['p_holm']))])
        for target,r in b[bench]['stopping']['calibration_selected_targets'].items():
            scal.append([NAMES[bench] if target=='3' else '',target,fixed(r['theta'],2),str(r['n_min']),
                         cost(r['calibration_cost']),cost(r['cost']),pct(r['accuracy'])])
    put('tab_s_oracles.tex','Fixed-pool accuracies and reference margins (\\%).','tab:s-oracles',
        'llrccccc',['Benchmark','Pool',r'$B$','One-coin',r'$O_{\rm cov}$',r'$O_{\rm mem}$',r'$g_{\rm cov}$',r'$d_{\rm mem}$'],soracle)
    put('tab_s_readouts.tex','Same-pool readout comparisons (\\%).','tab:s-readouts',
        r'llc>{\columncolor{methodshade}}ccccc',
        ['Benchmark','Pool','Majority','One-coin','Cal.-wtd',r'$\Delta_{\rm cw}$ [95\% CI]',r'$p$',r'$p_H$'],sread)
    put('tab_s_multicoin.tex','MMLU-Pro confusion-matrix and one-coin readouts (\\%).','tab:s-multicoin',
        r'l>{\columncolor{methodshade}}ccccc',
        ['Pool','One-coin','Multi-coin',r'$\Delta_{\rm mc}$ [95\% CI]',r'$p$',r'$p_H$'],smulti)
    put('tab_s_calibration_stopping.tex','Stopping policies selected by calibration target cost.','tab:s-calibration-stopping',
        'lrcrccc',['Benchmark','Target',r'$\theta$',r'$n_{\min}$','Cal. calls','Eval. calls',r'Acc. (\%)'],scal)
    rows=[]
    for i,r in enumerate(data['correlation_configurations']):
        if i and r['benchmark']!=data['correlation_configurations'][i-1]['benchmark']:rows.append(None)
        team='--'.join({'qwen':'Qwen','llama':'Llama','mistral':'Mistral'}[x] for x in r['team'])
        name=NAMES[r['benchmark']] if i==0 or r['benchmark']!=data['correlation_configurations'][i-1]['benchmark'] else ''
        rows.append([name,team,fixed(r['correlation'],3),pct(r['minimum_calibration_accuracy']),
                     pct(r['mean_calibration_accuracy']),pct(r['accuracy']),ci(r['paired_vs_single9']),
                     math(pv(r['paired_vs_single9']['p']))])
    put('tab_s_correlation.tex','Calibration correctness correlation and team effects (\\%).','tab:s-correlation',
        'llcccccc',['Benchmark','Team',r'$\rho$','Min. acc.','Mean acc.','Team acc.',r'$\Delta A$ [95\% CI]',r'$p$'],rows)
    manifest={'source_version':data['version'],'source_sha256':source_hash,
              'format':{'rates':'100x, one decimal, ROUND_HALF_UP','gains':'absolute 100x, signed',
                        'costs':'two decimals','p_values':'<0.001 or three decimals, unscaled',
                        'MmluWeightPFull':'includes comparison relation for use as p\\MmluWeightPFull',
                        'correlation':'three decimals, unscaled'},
              'macros':macro,'generated_files':{p:sha256(t.encode()).hexdigest() for p,t in out.items()}}
    out['data/render_manifest.json']=json.dumps(manifest,ensure_ascii=False,indent=2)+'\n'
    return out


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    outputs=render()
    for relative,text in outputs.items():
        path=HERE/relative
        if args.check:
            assert path.read_text(encoding='utf8')==text,f'Stale generated asset: {relative}'
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text,encoding='utf8')
    print(('CHECK PASS: ' if args.check else 'WROTE: ')+str(len(outputs))+' generated assets from current_results.json.')


if __name__=='__main__':main()
